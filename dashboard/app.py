    thread_benchmark = load_csv("thread_benchmark.csv")

    total = integer(sequential, "total_requests")
    success = integer(sequential, "successful_requests")
    failed = integer(sequential, "failed_requests")
    avg_response = num(sequential, "average_response_ms")

    labels = [f"{integer(r, 'input_size'):,}" for r in benchmark]
    seq_times = [num(r, "sequential_ms") for r in benchmark]
    par_times = [num(r, "parallel_ms") for r in benchmark]
    speedups = [num(r, "speedup") for r in benchmark]
    efficiencies = [num(r, "efficiency_percent") for r in benchmark]

    thread_labels = [str(integer(r, "threads")) for r in thread_benchmark]
    thread_times = [num(r, "parallel_ms") for r in thread_benchmark]

