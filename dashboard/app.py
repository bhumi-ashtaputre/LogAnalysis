    omp_analysis = num(parallel, "analysis_ms")
    current_threads = integer(parallel, "threads", 4)
    current_speedup = seq_analysis / omp_analysis if omp_analysis > 0 else 0.0
    current_efficiency = (current_speedup / current_threads) * 100 if current_threads else 0.0

