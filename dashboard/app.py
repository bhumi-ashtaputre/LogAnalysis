#!/usr/bin/env python3
"""Self-contained browser dashboard for Sequential vs OpenMP log analysis.

The dashboard intentionally contains only the project-analysis views and the
performance experiments required by the Parallel Programming rubric.
All graphs and tables are generated by this file using Python's standard
library; no Flask or external Python package is required.
"""

from __future__ import annotations

import csv
import html
import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
HOST = "127.0.0.1"
PORT = 8000


def load_json(name: str) -> dict:
    path = RESULTS / name
    if not path.exists():
        return {}
    try:
        with path.open(encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}


def load_csv(name: str) -> list[dict]:
    path = RESULTS / name
    if not path.exists():
        return []
    try:
        with path.open(encoding="utf-8", newline="") as f:
            return list(csv.DictReader(f))
    except OSError:
        return []


def num(row: dict, key: str, default: float = 0.0) -> float:
    try:
        return float(row.get(key, default))
    except (TypeError, ValueError):
        return default


def integer(row: dict, key: str, default: int = 0) -> int:
    try:
        return int(float(row.get(key, default)))
    except (TypeError, ValueError):
        return default


def esc(value) -> str:
    return html.escape(str(value))


def stat_card(title: str, value: str) -> str:
    return (
        '<div class="stat">'
        f'<div class="stat-title">{esc(title)}</div>'
        f'<div class="stat-value">{esc(value)}</div>'
        '</div>'
    )


def svg_line_chart(
    title: str,
    labels: list[str],
    series: list[tuple[str, list[float]]],
    suffix: str = "",
) -> str:
    width, height = 900, 360
    left, right, top, bottom = 72, 28, 52, 58
    plot_w, plot_h = width - left - right, height - top - bottom

    all_values = [v for _, values in series for v in values]
    if not all_values or not labels:
        return (
            '<div class="chart-card empty-chart"><h3>'
            f'{esc(title)}</h3><p>Run the benchmark to populate this graph.</p></div>'
        )

    y_max = max(max(all_values) * 1.15, 1.0)

    def x_pos(i: int) -> float:
        if len(labels) == 1:
            return left + plot_w / 2
        return left + plot_w * i / (len(labels) - 1)

    def y_pos(value: float) -> float:
        return top + plot_h - (value / y_max) * plot_h

    parts = [
        f'<div class="chart-card"><h3>{esc(title)}</h3>'
        f'<svg viewBox="0 0 {width} {height}" role="img" aria-label="{esc(title)}">'
    ]

    for step in range(5):
        value = y_max * step / 4
        y = y_pos(value)
        parts.append(
            f'<line x1="{left}" y1="{y:.1f}" x2="{width-right}" y2="{y:.1f}" class="grid"/>'
        )
        parts.append(
            f'<text x="{left-10}" y="{y+4:.1f}" text-anchor="end" class="axis">'
            f'{value:.1f}{esc(suffix)}</text>'
        )

    for i, label in enumerate(labels):
        x = x_pos(i)
        parts.append(
            f'<text x="{x:.1f}" y="{height-24}" text-anchor="middle" class="axis">'
            f'{esc(label)}</text>'
        )

    for series_index, (name, values) in enumerate(series):
        points = " ".join(
            f"{x_pos(i):.1f},{y_pos(v):.1f}" for i, v in enumerate(values)
        )
        parts.append(f'<polyline points="{points}" class="line line-{series_index}"/>')
        for i, value in enumerate(values):
            parts.append(
                f'<circle cx="{x_pos(i):.1f}" cy="{y_pos(value):.1f}" '
                f'r="4" class="dot dot-{series_index}"/>'
            )

    legend_x = left
    for i, (name, _) in enumerate(series):
        x = legend_x + i * 190
        parts.append(
            f'<line x1="{x}" y1="20" x2="{x+28}" y2="20" class="line line-{i}"/>'
        )
        parts.append(f'<text x="{x+36}" y="24" class="legend">{esc(name)}</text>')

    parts.append("</svg></div>")
    return "".join(parts)


def build_correctness_rows(sequential: dict, parallel: dict) -> tuple[str, bool]:
    metrics = [
        ("Total Requests", sequential.get("total_requests"), parallel.get("total_requests"), "int"),
        ("Successful Requests", sequential.get("successful_requests"), parallel.get("successful_requests"), "int"),
        ("Failed Requests", sequential.get("failed_requests"), parallel.get("failed_requests"), "int"),
        ("Average Response (ms)", sequential.get("average_response_ms"), parallel.get("average_response_ms"), "float"),
        ("HTTP Status Counts", sequential.get("status_counts", {}), parallel.get("status_counts", {}), "dict"),
        ("Top URL", (sequential.get("top_urls") or [{}])[0].get("url", ""),
         (parallel.get("top_urls") or [{}])[0].get("url", ""), "text"),
    ]

    rows = []
    all_match = True
    for name, seq_value, omp_value, kind in metrics:
        if kind == "int":
            seq_display = f"{int(seq_value or 0):,}"
            omp_display = f"{int(omp_value or 0):,}"
            match = int(seq_value or 0) == int(omp_value or 0)
        elif kind == "float":
            seq_display = f"{float(seq_value or 0):.3f}"
            omp_display = f"{float(omp_value or 0):.3f}"
            match = abs(float(seq_value or 0) - float(omp_value or 0)) < 1e-9
        elif kind == "dict":
            seq_display = esc(seq_value or {})
            omp_display = esc(omp_value or {})
            match = (seq_value or {}) == (omp_value or {})
        else:
            seq_display = esc(seq_value)
            omp_display = esc(omp_value)
            match = seq_value == omp_value

        all_match = all_match and match
        rows.append(
            f"<tr><td>{esc(name)}</td><td>{seq_display}</td><td>{omp_display}</td>"
            f'<td><span class="match {"yes" if match else "no"}">'
            f'{"MATCH" if match else "MISMATCH"}</span></td></tr>'
        )

    return "".join(rows), all_match


